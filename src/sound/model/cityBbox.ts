/** 外框（不外擴）包含該點的所有縣市 */
export function citiesContaining(lon: number, lat: number): string[] {
  return Object.entries(CITY_BBOX)
    .filter(([, [w, s, e, n]]) => lon >= w && lon <= e && lat >= s && lat <= n)
    .map(([c]) => c)
    .sort();
}

