import { describe, expect, it } from "vitest";
import { COUNTRIES, countryForPoint, isCountryCode } from "../countries";

describe("countries", () => {
  it("國碼與 chip 一致、bbox 都是合法矩形", () => {
    for (const country of COUNTRIES) {
      expect(country.chip).toBe(country.code);
      expect(country.labelKey).toBe(`country.${country.code}`);
      for (const [west, south, east, north] of country.bboxes) {
        expect(west).toBeLessThan(east);
        expect(south).toBeLessThan(north);
      }
    }
    expect(isCountryCode("JP")).toBe(true);
    expect(isCountryCode("jp")).toBe(false);
  });

  it.each([
    ["台北", 121.53, 25.05, "TW"],
    ["金門", 118.3, 24.45, "TW"],
    ["馬祖", 119.95, 26.15, "TW"],
    ["澎湖", 119.57, 23.57, "TW"],
    ["蘭嶼", 121.55, 22.05, "TW"],
    ["小金門", 118.25, 24.43, "TW"],
    ["東引", 120.49, 26.37, "TW"],
    ["東京", 139.77, 35.68, "JP"],
    ["大阪", 135.5, 34.69, "JP"],
    ["札幌", 141.35, 43.06, "JP"],
    ["福岡", 130.4, 33.59, "JP"],
    ["那霸", 127.68, 26.21, "JP"],
    ["與那國", 123.0, 24.47, "JP"],
    ["石垣", 124.16, 24.34, "JP"],
    ["巴黎", 2.35, 48.86, "FR"],
    ["馬賽", 5.37, 43.3, "FR"],
    ["阿雅克肖", 8.74, 41.93, "FR"],
    ["史特拉斯堡", 7.75, 48.58, "FR"],
    ["里爾", 3.06, 50.63, "FR"],
    ["敦克爾克", 2.37, 51.03, "FR"],
    ["梅斯", 6.18, 49.12, "FR"],
    ["牟羅茲", 7.34, 47.75, "FR"],
    ["貝爾福", 6.86, 47.64, "FR"],
    ["安錫", 6.13, 45.9, "FR"],
    ["尼斯", 7.26, 43.7, "FR"],
    ["佩皮尼昂", 2.9, 42.7, "FR"],
    ["波爾多", -0.58, 44.84, "FR"],
    ["布雷斯特", -4.49, 48.39, "FR"],
    ["巴斯蒂亞", 9.45, 42.7, "FR"],
  ] as const)("%s → %s", (_name, lng, lat, code) => {
    expect(countryForPoint(lng, lat)).toBe(code);
  });

  it.each([
    ["釣魚台一帶", 123.5, 25.75],
    ["首爾", 126.98, 37.57],
    ["釜山", 129.07, 35.18],
    ["濟州", 126.53, 33.5],
    ["上海", 121.47, 31.23],
    ["廈門", 118.09, 24.48],
    ["福州", 119.3, 26.08],
    ["黃岐半島", 119.9, 26.33],
    ["日內瓦", 6.14, 46.2],
    ["洛桑", 6.63, 46.52],
    ["巴塞爾", 7.59, 47.56],
    ["杜林", 7.68, 45.07],
    ["安道爾", 1.52, 42.51],
    ["巴塞隆納", 2.17, 41.39],
    ["聖塞巴斯提安", -1.98, 43.32],
    ["布魯塞爾", 4.35, 50.85],
    ["蒙斯", 3.95, 50.45],
    ["圖爾奈", 3.39, 50.6],
    ["伊珀爾", 2.88, 50.85],
    ["盧森堡", 6.13, 49.61],
    ["薩爾布呂肯", 7.0, 49.23],
    ["弗萊堡", 7.85, 47.99],
    ["卡爾斯魯厄", 8.4, 49.0],
    ["薩丁尼亞北端", 9.4, 41.2],
    ["太平洋", 150, 20],
  ] as const)("%s 不屬於任何國家（鄰國或爭議海域）", (_name, lng, lat) => {
    expect(countryForPoint(lng, lat)).toBeUndefined();
  });
});
